function y = f_tv_delay_intfrac_v3(x, tau, M)
%------------------------------------------------------------
%------------------------------------------------------------
% 时变时延（整数 + 分数），每个采样点对应不同的分数延时滤波器
% windowed-sinc 实现
%
% x   : 输入信号 [N x 1] (实或复)
% tau : 总时延轨迹 [N x 1]，任意实数（可>1，可<0）
% M   : sinc 半长度，核长 = 2M+1
%
% y   : 输出信号 [N x 1]
%
% 模型：
%   tau[n] = D[n] + delta[n], delta[n]∈[0,1)
%   y[n] = sum_{m=-M..M} x[n - D[n] - m] * sinc(m-delta[n]) * w[m]
%------------------------------------------------------------
% 修改历史:
%  ---------------------------------------------------------------------------------
%  版本      时间        修改者      修改内容                                  备注
%  ---------------------------------------------------------------------------------
%  v3    2026-05-20     [罗韬]     [极致矢量化优化的时变分数时延滤波器]
%
%------------------------------------------------------------
    % 确保输入为列向量
    x = x(:);
    tau = tau(:);
    N = length(x);

    % ===== Step 1: 动态分解整数 + 分数 =====
    D = round(tau);
    delta = tau - D;

    % ===== Step 2: 利用隐式扩展生成所有系数矩阵 =====
    m = (-M:M).';         % 列向量: (2M+1) x 1
    n = 1:N;              % 行向量: 1 x N

    % 隐式扩展: (2M+1)x1 - 1xN -> 生成 (2M+1) x N 的系数矩阵 H
    % H 的每一列就是原来循环里对应第 n 个采样点的 h
    H = sinc(m - delta.');

    % 归一化
    % H = H ./ sum(H, 1);         % 这是分数时延的正确做法
    H = H ./ vecnorm(H, 2, 1);    % 为了与倪和马的信道函数对上

    % ===== Step 3: 矩阵化寻址提取 x =====
    % 计算所有 (2M+1) x N 的目标索引
    Idx = n - D.' - m;

    % 生成边界掩码 (Mask)，找出哪些索引在 [1, N] 范围内
    valid_mask = (Idx >= 1) & (Idx <= N);

    % 预分配数据矩阵 (使用 'like', x 兼容 x 是复数的情况)
    X_mat = zeros(2*M+1, N, 'like', x);

    % 利用逻辑索引，一次性把 x 中对应的值填入矩阵
    X_mat(valid_mask) = x(Idx(valid_mask));

    % ===== Step 4: 逐元素相乘并按列求和 =====
    y = sum(X_mat .* H, 1).';
end